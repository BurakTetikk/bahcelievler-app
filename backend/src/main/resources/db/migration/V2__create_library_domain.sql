CREATE TABLE books (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(200) NOT NULL,
    author VARCHAR(150) NOT NULL,
    isbn VARCHAR(20),
    publisher VARCHAR(150),
    publication_year INTEGER,
    category VARCHAR(100),
    description TEXT,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_books_isbn UNIQUE (isbn),
    CONSTRAINT ck_books_publication_year CHECK (publication_year IS NULL OR publication_year BETWEEN 0 AND 3000)
);

CREATE TABLE book_copies (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    book_id BIGINT NOT NULL,
    inventory_code VARCHAR(50) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'AVAILABLE',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_book_copies_book FOREIGN KEY (book_id) REFERENCES books (id) ON DELETE RESTRICT,
    CONSTRAINT uk_book_copies_inventory_code UNIQUE (inventory_code),
    CONSTRAINT ck_book_copies_status CHECK (status IN ('AVAILABLE', 'ON_LOAN', 'LOST', 'DAMAGED'))
);
CREATE INDEX ix_book_copies_book_id ON book_copies (book_id);
CREATE INDEX ix_book_copies_status ON book_copies (status);

CREATE TABLE borrowers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name VARCHAR(80) NOT NULL,
    last_name VARCHAR(80) NOT NULL,
    email VARCHAR(254),
    phone VARCHAR(30),
    notes TEXT,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX ix_borrowers_name ON borrowers (last_name, first_name);
CREATE INDEX ix_borrowers_active ON borrowers (active);

CREATE TABLE loans (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    book_copy_id BIGINT NOT NULL,
    borrower_id BIGINT NOT NULL,
    loan_date DATE NOT NULL,
    due_date DATE NOT NULL,
    return_date DATE,
    notes TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_loans_book_copy FOREIGN KEY (book_copy_id) REFERENCES book_copies (id) ON DELETE RESTRICT,
    CONSTRAINT fk_loans_borrower FOREIGN KEY (borrower_id) REFERENCES borrowers (id) ON DELETE RESTRICT,
    CONSTRAINT ck_loans_due_date CHECK (due_date >= loan_date),
    CONSTRAINT ck_loans_return_date CHECK (return_date IS NULL OR return_date >= loan_date)
);
CREATE UNIQUE INDEX uk_loans_active_book_copy ON loans (book_copy_id) WHERE return_date IS NULL;
CREATE INDEX ix_loans_borrower_loan_date ON loans (borrower_id, loan_date DESC);
CREATE INDEX ix_loans_due_date_active ON loans (due_date) WHERE return_date IS NULL;
